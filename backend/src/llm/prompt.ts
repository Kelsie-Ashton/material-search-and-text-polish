/**
 * 润色用的提示词（任务 6.5）。
 *
 * ## 为什么提示词单独一个文件、还带版本号
 *
 * `polish_results.prompt_version` 是 schema 里的一列。留着一个版本的润色结果
 * 却不记下它是用哪版提示词跑出来的，两件事都做不成：**结果没法比较**
 * （换个说法重跑，差异是提示词带来的还是模型带来的？），**也没法回退**。
 * 所以版本号写在这里，落库时带上。
 *
 * ## 提示词为什么写成这样
 *
 * 输入的来源决定了它有几个绕不开的毛病，提示词里必须针对性地交代：
 *
 * 1. **文字是机器转写或字幕解析来的**，会有识别错字、口语重复（「就是就是」）、
 *    满篇语气词、以及**没有标点**。不说明这一点，模型会把这些当成原文风格照搬。
 * 2. **模型不知道这些字是「素材里的」**，很容易顺手补充它自己知道的背景知识。
 *    而用户要的是「把这个素材里说的整理好」，不是「写一篇关于这个话题的文章」——
 *    所以「不编造素材里没有的内容」这条必须写死。
 * 3. **输出会被直接贴到别处用**，所以不能带前言后记、不能包代码块、
 *    不能用 markdown 标题——用户要的是文案正文本身。
 */

/** 提示词版本。改动提示词时**必须**跟着改，否则新旧结果在库里分不出来。 */
export const PROMPT_VERSION = 'polish-v1'

export const SYSTEM_PROMPT = [
  '你在帮一位做二次创作的人，把从素材里提取出来的文字整理成一段可以直接使用的文案。',
  '',
  '关于这些文字，你需要知道：',
  '- 它们来自语音转写或字幕文件，可能带识别错字、口语重复、语气词，也可能整段没有标点。',
  '- 它们是素材里**实际说过的话**，不是别人写的文章。',
  '',
  '请这样处理：',
  '- 把口语整理成通顺的书面表达，补上标点，去掉重复和纯语气词。',
  '- **严格保留原意**。不要补充素材里没有的信息，不要加入你自己的背景知识或评论。',
  '- 如果原文有识别错字，按上下文改成最可能正确的那个词；拿不准就保留原样。',
  '- 不要臆造说话人、时间、地点这类原文里没有的细节。',
  '',
  '直接输出整理好的文案正文。不要写「以下是整理后的文案」这类前言，',
  '不要用 markdown 标题或代码块，不要加任何解释。',
].join('\n')

/**
 * 拼出这一次要发给模型的用户消息。
 *
 * 带上素材名不是装饰：同一批素材里往往有同一部剧的不同集，
 * 用户在结果列表里要能分清这条润色是对着谁跑的。
 */
export function buildPolishInput(input: { assetName: string; text: string }): string {
  return [`素材：${input.assetName}`, '', '以下是这个素材里提取出的文字：', '', input.text].join(
    '\n',
  )
}
